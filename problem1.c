/*
 * 문제 1: 다음 프로그램을 실행하고, 무엇을 하는 프로그램인지 말하라.
 *
 * [출력 결과와 설명]
 * 이 프로그램은 1부터 100까지의 정수 중에서
 * 3의 배수이면서 5의 배수이고 7의 배수인 수(즉, 105의 배수)를 출력합니다.
 * 1~100 범위에서 3, 5, 7 모두의 배수는 존재하지 않으므로 아무것도 출력되지 않습니다.
 * (105가 100을 초과하므로 출력값 없음)
 */

#include <stdio.h>
int main(void)
{
    int count = 1, i;
    for(i = 1; i <= 100; i++) {
        if ( i%3 == 0 && i%5 == 0 && i%7 == 0 )
            printf("%3d ", i);
    }
    return 0;
}
