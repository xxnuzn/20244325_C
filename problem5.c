/*
 * 문제 5: 다음 프로그램을 실행하고, 그 결과를 써라.
 *
 * [출력 결과]
 * 987654321
 * 98765432
 * 9876543
 * 987654
 * 98765
 * 9876
 * 987
 * 98
 * 9
 *
 * [설명]
 * i = 1~9 (행), j = 9~0 (감소)
 * j >= i 일 때 숫자(1자리) 출력, j < i 일 때 공백 출력
 * → 오른쪽에서 줄어드는 숫자 패턴 (j=0은 출력 안 됨, j>=i 조건에서 제외)
 */

#include <stdio.h>
int main(void)
{
    int i, j;
    for (i = 1; i <= 9; i++)
    {
        for (j = 9; j >= 0; j--)
        {
            if (j >= i) printf("%d", j);
            else putchar(' ');
        }
        putchar('\n');
    }
    return 0;
}
