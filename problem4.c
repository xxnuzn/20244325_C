/*
 * 문제 4: 다음 프로그램을 작성하고, 그 결과를 쓰고, 어떤 일을 하는 프로그램인지 설명하시오.
 *
 * [프로그램 설명]
 * 정수를 5개 연속해서 입력받아, 각 정수의 자릿수를 역순으로 출력하는 프로그램입니다.
 * 예) 입력: 12345  →  출력: 5 4 3 2 1
 * 입력한 정수의 마지막 자리수부터 차례로 % 10 연산으로 추출하고,
 * / 10 으로 나누어 자릿수를 줄여가면서 0이 될 때까지 반복합니다.
 *
 * [실행 결과 예시]
 * 정수를 5개 연속해서 입력하세요.
 * 12345
 *  출력 결과는 >>> 5 4 3 2 1
 */

#include <stdio.h>
int main(void)
{
    int value;   // 입력한 정수 값
    int r_digit; // 출력할 마지막 자릿수

    printf("정수를 5개 연속해서 입력하세요.\n");
    scanf("%d", &value);
    printf("\n 출력 결과는 >>> ");
    do
    {
        r_digit = value % 10;
        printf("%d ", r_digit);
        value = value / 10;
    } while( value != 0 );
    printf("\n");
    return 0;
}
